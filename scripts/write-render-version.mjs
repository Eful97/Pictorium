import fs from "node:fs/promises"
import path from "node:path"
import crypto from "node:crypto"
import { fileURLToPath } from "node:url"

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")

// File il cui contenuto determina l'output visivo del poster. Quando uno di
// questi cambia, RENDER_VERSION cambia da sola: la cache server e le URL
// Stremio vengono invalidate senza dover bumpare nulla a mano.
// NB: NON includere `render-version.ts` (è l'output dello script).
// File esclusi intenzionalmente: poster-runtime-cache.ts, cache.ts,
// justwatch.ts, flixpatrol.ts, ratings.ts — influenzano ranking/cache ma
// non il rendering visivo byte-level; non devono invalidare rv.
const RENDER_FILES = [
  "src/app/api/poster/[type]/[id]/route.ts",
  "src/lib/accent-color.ts",
  "src/lib/badge-priority.ts",
  "src/lib/badge-styles.ts",
  "src/lib/badge-svg-shared.ts",
  "src/lib/badges.ts",
  "src/lib/blur.ts",
  "src/lib/config-token.ts",
  "src/lib/fonts.ts",
  "src/lib/image-utils.ts",
  "src/lib/logo-layout.ts",
  "src/lib/logo-selection.ts",
  "src/lib/network-svgs.ts",
  "src/lib/poster-auto-fit.ts",
  "src/lib/poster-badge.ts",
  "src/lib/poster-config.ts",
  "src/lib/poster-fit-adjust.ts",
  "src/lib/poster-fit-score.ts",
  "src/lib/poster-render-helpers.ts",
  "src/lib/poster-rotation.ts",
  "src/lib/poster-service.ts",
  "src/lib/poster-url.ts",
  "src/lib/release-badge.ts",
  "src/lib/stremio-poster-params.ts",
  "src/lib/stremio-poster-url.ts",
  "src/lib/subgenres.ts",
  "src/lib/svg-badge.ts",
  "src/assets/fonts/Inter-Black.ttf",
  "src/assets/fonts/Inter-Bold.ttf",
  "src/assets/fonts/Inter-Regular.ttf",
  "src/assets/fonts/NotoSansSymbols2-Regular.ttf",
  "src/assets/fonts/Rubik-Black.ttf",
  "src/assets/fonts/Rubik-Bold.ttf",
  "src/assets/fonts/Rubik-Regular.ttf",
]

const outputPath = path.join(rootDir, "src", "lib", "render-version.ts")

// Normalizza i fine riga (CRLF -> LF): la working copy su Windows usa CRLF,
// mentre CI/Linux usa LF. Senza normalizzazione l'hash differirebbe tra le
// due, invalidando la cache in modo non deterministico.
async function readNormalized(filePath) {
  const raw = await fs.readFile(filePath, "utf-8")
  return raw.replace(/\r\n?/g, "\n")
}

const hash = crypto.createHash("sha256")
for (const rel of RENDER_FILES) {
  const content = await readNormalized(path.join(rootDir, rel))
  hash.update(rel)
  hash.update("\0")
  hash.update(content)
  hash.update("\0")
}
const version = hash.digest("hex").slice(0, 10)

const output = [
  "// AUTO-GENERATED by scripts/write-render-version.mjs — do not edit manually.",
  "// Cambia automaticamente quando i file di rendering (badges, blur, logo, font,",
  "// route poster) cambiano: invalida cache server e URL Stremio senza bump manuali.",
  `export const RENDER_VERSION = "${version}"`,
  "export const POSTER_URL_VERSION = RENDER_VERSION",
  "",
].join("\n")

await fs.mkdir(path.dirname(outputPath), { recursive: true })
await fs.writeFile(outputPath, output)
