import fs from "node:fs/promises"
import path from "node:path"
import { execFileSync } from "node:child_process"
import { fileURLToPath } from "node:url"

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const packagePath = path.join(rootDir, "package.json")
const outputPath = path.join(rootDir, "src", "generated", "app-version.ts")

const rawPackage = await fs.readFile(packagePath, "utf-8")
const packageJson = JSON.parse(rawPackage)

if (!packageJson || typeof packageJson.version !== "string" || packageJson.version.trim() === "") {
  throw new Error("package.json version is missing")
}

// La versione dell'app segue il tag pubblicato: l'ultimo tag versione
// (vX.Y.Z) raggiungibile da HEAD vince sempre, così APP_VERSION resta in
// linea col tag senza bump manuali del package.json a ogni rilascio.
// Senza tag/git (es. build Docker senza .git) si ricade sulla logica legacy:
// major.minor dal package.json + patch = commit da quando la versione fu
// impostata. APP_COMMIT è lo SHA corto di HEAD (debug "quale commit gira?");
// "unknown" quando git non è disponibile.
// Se git non è disponibile (es. build Docker senza .git), si ricade sulla versione base del package.json.
const baseVersion = packageJson.version.trim()
const [major, minor, basePatch = "0"] = baseVersion.split(".")
let version = baseVersion
let commit = "unknown"
try {
  try {
    commit = execFileSync("git", ["rev-parse", "--short", "HEAD"], {
      cwd: rootDir,
      encoding: "utf-8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim() || "unknown"
  } catch {}
  if (!/^[0-9a-f]{4,40}$/i.test(commit)) commit = "unknown"
  // Fonte primaria: ultimo tag vX.Y.Z (tag non-versione ignorati).
  let tagVersion = null
  try {
    const rawTag = execFileSync(
      "git",
      ["describe", "--tags", "--abbrev=0", "--match", "v[0-9]*.[0-9]*.[0-9]*"],
      {
        cwd: rootDir,
        encoding: "utf-8",
        stdio: ["ignore", "pipe", "ignore"],
      }
    ).trim()
    const tagMatch = /^v(\d+\.\d+\.\d+)$/.exec(rawTag)
    if (tagMatch) tagVersion = tagMatch[1]
  } catch {}
  if (tagVersion) {
    version = tagVersion
  } else {
  let headVersion = null
  try {
    const headPkg = execFileSync("git", ["show", "HEAD:package.json"], {
      cwd: rootDir,
      encoding: "utf-8",
      stdio: ["ignore", "pipe", "ignore"],
    })
    headVersion = JSON.parse(headPkg)?.version?.trim()
  } catch {}

  if (headVersion && headVersion !== baseVersion) {
    // Versione modificata localmente ma non ancora committata: parte da basePatch
    version = `${major}.${minor}.${basePatch}`
  } else {
    // Trova l'ultimo commit che ha modificato il campo version in package.json
    const introCommit = execFileSync(
      "git",
      ["log", "-G", '"version":', "-n", "1", "--pretty=format:%H", "package.json"],
      {
        cwd: rootDir,
        encoding: "utf-8",
        stdio: ["ignore", "pipe", "ignore"],
      }
    ).trim()

    if (introCommit && /^[0-9a-f]{40}$/i.test(introCommit)) {
      const commitCount = execFileSync(
        "git",
        ["rev-list", "--count", `${introCommit}..HEAD`],
        {
          cwd: rootDir,
          encoding: "utf-8",
          stdio: ["ignore", "pipe", "ignore"],
        }
      ).trim()

      if (/^\d+$/.test(commitCount)) {
        const patchNum = (parseInt(basePatch, 10) || 0) + parseInt(commitCount, 10)
        version = `${major}.${minor}.${patchNum}`
      }
    }
  }
  }
} catch {}

// Override esplicito (`APP_VERSION=x.y.z`): vince su tutto. Serve alle build CI,
// dove il build context esclude .git (.dockerignore) e il conteggio commit non è
// disponibile: senza override l'immagine pubblicata si dichiarerebbe sempre con
// la versione base del package.json invece di quella di rilascio.
const overrideVersion = (process.env.APP_VERSION ?? "").trim()
if (overrideVersion) {
  if (/^\d+\.\d+\.\d+$/.test(overrideVersion)) {
    version = overrideVersion
  } else {
    console.warn(
      `[app-version] APP_VERSION "${overrideVersion}" non è x.y.z: override ignorato`
    )
  }
}

const output = [
  "// AUTO-GENERATED by scripts/write-app-version.mjs — do not edit manually.",
  "// Versione automatica: ultimo tag vX.Y.Z raggiungibile da HEAD (sempre in",
  "// linea col tag pubblicato); fallback su package.json + conteggio commit",
  "// quando non ci sono tag/git disponibili.",
  "// APP_COMMIT: SHA corto di HEAD (quale commit gira in produzione);",
  '// "unknown" senza git.',
  `export const APP_VERSION = ${JSON.stringify(version)}`,
  `export const APP_COMMIT = ${JSON.stringify(commit)}`,
  "",
].join("\n")

await fs.mkdir(path.dirname(outputPath), { recursive: true })
await fs.writeFile(outputPath, output)
