for (const width of [390, 1280]) {
  test(`light settings text at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 })
    await page.addInitScript(() => localStorage.setItem("pictorium_ui_theme", "light"))
    await page.goto("/")
    const logo = page.locator(".header-logo-light:visible").first()
    await expect(logo).toHaveAttribute("src", "/pictorium-light.svg")
    await expect.poll(() => logo.evaluate((el: HTMLImageElement) => el.complete && el.naturalWidth > 0)).toBe(true)
    await page.getByRole("button", { name: /Impostazioni/i }).click()
    for (const [tab, label] of [["badge", "Badge"], ["trasforma", "Trasforma"], ["prefs", "Preferenze"], ["data", "Dati & Cache"]]) {
      if (width < 640) await page.locator("#mobile-settings-category").selectOption(tab)
      else await page.getByRole("tab", { name: label, exact: true }).click()
      const controls = page.getByTestId("settings-controls").filter({ visible: true })
      await expect(controls).toBeVisible()
      const whiteLabels = await controls.evaluate((root) => Array.from(root.querySelectorAll<HTMLElement>("*"))
        .filter((el) => el.checkVisibility() && Array.from(el.childNodes).some((node) => node.nodeType === Node.TEXT_NODE && node.textContent?.trim()))
        .filter((el) => {
          const color = getComputedStyle(el).color.match(/[\d.]+/g)?.slice(0, 3).map(Number)
          return color?.every((value) => value > 235) && !el.closest(".bg-accent-orange, .bg-rose-500, .badge-style-preview")
        })
        .map((el) => ({ text: el.textContent?.trim(), className: el.className })))
      expect(whiteLabels, `White labels in ${tab}`).toEqual([])
      await controls.screenshot({ path: `test-results/settings-${tab}-light-${width}.png`, animations: "disabled" })
    }
  })
}

