import { test, expect } from "@playwright/test"

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem("pictorium_profile_id", "e2e")
    localStorage.setItem("pictorium_profile_stateless", "1")
    localStorage.setItem("pictorium_onboarding_done", "true")
    localStorage.setItem("preferred_lang", "it")
  })
})

for (const width of [390, 1280]) {
  test(`theme picker and light surfaces at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 })
    const errors: string[] = []
    page.on("pageerror", (error) => errors.push(error.message))
    await page.goto("/")
    await expect(page.getByPlaceholder(/cerca/i)).toBeVisible()
    const darkLogoBounds = (await page.locator(".header-logo-dark:visible").first().boundingBox())!
    const trigger = page.getByRole("button", { name: "Tema", exact: true })
    await expect(trigger).toBeVisible()
    expect((await trigger.boundingBox())!.y).toBeLessThan(70)
    await expect(page.getByRole("navigation").getByRole("button", { name: "Tema", exact: true })).toHaveCount(0)
    await expect(page.getByTestId("home-status").getByRole("button", { name: "Tema", exact: true })).toHaveCount(0)
    await trigger.click()
    await expect(page.getByRole("radiogroup", { name: "Tema" })).toBeVisible()
    const menuBounds = (await page.getByRole("radiogroup", { name: "Tema" }).boundingBox())!
    expect(menuBounds.x).toBeGreaterThanOrEqual(0)
    expect(menuBounds.x + menuBounds.width).toBeLessThanOrEqual(width)
    await page.getByRole("radio", { name: "Chiaro", exact: true }).click()
    await expect(page.locator("html")).toHaveAttribute("data-theme", "light")
    const lightLogoBounds = (await page.locator(".header-logo-light:visible").first().boundingBox())!
    expect(lightLogoBounds.width).toBeCloseTo(darkLogoBounds.width, 0)
    expect(lightLogoBounds.height).toBeCloseTo(darkLogoBounds.height, 0)
    await expect(page.getByRole("radiogroup")).toHaveCount(0)
    expect(await page.locator("body").evaluate((el) => getComputedStyle(el).backgroundColor)).toBe("rgb(242, 238, 231)")
    expect(await page.evaluate(() => localStorage.getItem("pictorium_theme"))).toBe("dark")
    expect(await page.evaluate(() => localStorage.getItem("pictorium_ui_theme"))).toBe("light")
    await page.screenshot({ path: `test-results/theme-light-${width}.png`, fullPage: true, animations: "disabled" })
    await page.reload()
    await expect(page.locator("html")).toHaveAttribute("data-theme", "light")
    await trigger.click()
    await page.getByRole("radio", { name: "Sistema", exact: true }).click()
    await page.emulateMedia({ colorScheme: "dark" })
    await expect(page.locator("html")).toHaveAttribute("data-theme", "dark")
    await page.emulateMedia({ colorScheme: "light" })
    await expect(page.locator("html")).toHaveAttribute("data-theme", "light")
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole("button", { name: /Impostazioni/i }).click()
    if (width < 640) await page.locator("#mobile-settings-category").selectOption("prefs")
    else await page.getByRole("tab", { name: "Preferenze" }).click()
    await expect(page.getByRole("radio", { name: "Chiaro", exact: true })).toBeVisible()
    await page.screenshot({ path: `test-results/theme-settings-${width}.png`, fullPage: true, animations: "disabled" })
    expect(errors).toEqual([])
  })
}

